-- Ставка группы объявлений. До неё ставка в схеме жила только на фразе
-- (`Keyword.bid`), то есть на уровне, которого у VK нет вообще: там показы
-- покупаются аудиториями, а цена задаётся на группе. Применённая карточка ставки
-- VK оседала только в кабинете — у нас её было некуда положить.
--
-- Обратная совместимость: колонка nullable и без умолчания. В Postgres 16 это
-- правка каталога без переписывания таблицы, существующие строки остаются с NULL,
-- и код, который колонку не читает, ничего не замечает. Backfill не делается
-- намеренно: значения ставок в базе нет ни в каком виде (в `ChangeLog` лежат
-- только решения, а не текущее состояние — и брать состояние из журнала мы уже
-- признали ошибкой), поэтому единственный честный источник — ближайшая загрузка
-- кабинета, которая колонку и заполнит.
--
-- NULL здесь значит «ручной ставки нет» (автостратегия назначает цену сама), а не
-- ноль: нулевая ставка у площадки — это другое утверждение, и путать их нельзя.
--
-- Явная транзакция: Prisma 7 файл миграции в неё не заворачивает и выполняет
-- statement'ы по одному. Statement здесь пока один, но частично применённая
-- миграция помечается упавшей, и дальше `migrate deploy` отвечает P3009 и на новом
-- образе, и на старом — то есть прод-стек не поднимется вовсе. BEGIN/COMMIT стоит
-- ноль и снимает этот риск заранее, в том числе у следующего, кто допишет сюда шаг.
BEGIN;

-- AlterTable
ALTER TABLE "AdGroup" ADD COLUMN     "bid" DECIMAL(12,2);

COMMIT;
