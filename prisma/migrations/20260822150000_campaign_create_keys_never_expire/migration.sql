-- Ключи создания кампаний не должны истекать — но до этой миграции не истекали
-- только новые.
--
-- `campaigns.create` — единственная память о том, что кампания по этой позиции
-- плана уже заведена в кабинете. Код перестал ставить ей срок (см.
-- `CAMPAIGN_KEY_NEVER_EXPIRES_AT` в `src/campaigns/idempotency.ts`), однако строки,
-- записанные раньше, сохранили `expiresAt = created + 90 дней`, а
-- `purgeExpiredIdempotencyKeys` удаляет просроченное по всем scope без разбора.
-- То есть в день чистки уже созданная кампания становится для нас «нетронутой», и
-- первый же ✅ заводит вторую с тем же именем и тем же дневным бюджетом. Клиент
-- платит дважды, а увидит это не он и не мы, а его отчёт в конце месяца.
--
-- Дата вместо NULL: колонка `expiresAt` в этой таблице обязательная, и делать её
-- nullable ради одного scope — менять смысл поля у всех остальных. `9999-12-31`
-- читается как «никогда» и совпадает с тем, что пишет код.
--
-- Условие по `expiresAt` оставляет миграцию идемпотентной: повторный прогон на уже
-- исправленной базе не трогает ни одной строки.
--
-- Явная транзакция: Prisma 7 файл миграции в неё не заворачивает, а частично
-- применённая миграция помечается упавшей — дальше `migrate deploy` отвечает P3009
-- и прод-стек не поднимается вовсе.
BEGIN;

UPDATE "IdempotencyKey"
SET "expiresAt" = TIMESTAMP '9999-12-31 00:00:00'
WHERE "scope" = 'campaigns.create'
  AND "expiresAt" < TIMESTAMP '9999-12-31 00:00:00';

COMMIT;
