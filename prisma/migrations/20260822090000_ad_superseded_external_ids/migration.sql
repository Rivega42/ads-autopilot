-- Связь «строка → внешние id, которые она оставила позади при правке текста»
-- переезжает из `ChangeLog` на саму строку. Журнал — про историю: он растёт вместе
-- со всем проектом, а выборка по нему отвечала на вопрос о текущем состоянии,
-- перебирая всё, что когда-либо записывала модерация по этим объявлениям.
--
-- Обратная совместимость: колонка добавляется nullable и без умолчания — это правка
-- каталога без переписывания таблицы, и существующие строки остаются с NULL. Prisma
-- читает NULL-список как пустой, то есть «ничего не заменяли» — ровно то поведение,
-- что было до колонки; код, который колонку не пишет, ничего не замечает.
--
-- Backfill той же миграцией, а не отдельным шагом: строк со связью единицы (это следы
-- неудавшейся уборки в VK), UPDATE по ним стоит один проход журнала, а между ALTER и
-- отложенным шагом любой прогон загрузки увидел бы пустую колонку и завёл бы под
-- погашенный баннер работающее объявление — то есть вернул бы ровно тот дефект, ради
-- которого колонка и появилась. Отбор тот же, что делала загрузка: `externalIdBefore`
-- есть, непустой и не совпадает с `externalIdAfter` (у Директа замены нет, и пары
-- полей в записи журнала тоже).
--
-- Явная транзакция: Prisma 7 файл миграции в неё не заворачивает и выполняет
-- statement'ы по одному. Упади UPDATE после ALTER — база осталась бы с пустой
-- колонкой и упавшей миграцией, а дальше `migrate deploy` отвечает P3009 и на новом
-- образе, и на старом, то есть прод-стек не поднимется вовсе.
BEGIN;

-- AlterTable
ALTER TABLE "Ad" ADD COLUMN     "supersededExternalIds" TEXT[];

-- Backfill из журнала: связь для уже накопленных строк не теряется.
UPDATE "Ad" a
SET "supersededExternalIds" = j.ids
FROM (
  SELECT
    c."entityId" AS ad_id,
    array_agg(DISTINCT c."newValue" ->> 'externalIdBefore') AS ids
  FROM "ChangeLog" c
  WHERE c."entityType" = 'AD'
    AND c."action" = 'moderation_rewrite'
    AND c."newValue" ->> 'externalIdBefore' IS NOT NULL
    AND c."newValue" ->> 'externalIdBefore' <> ''
    AND c."newValue" ->> 'externalIdBefore' IS DISTINCT FROM c."newValue" ->> 'externalIdAfter'
  GROUP BY c."entityId"
) j
WHERE a."id" = j.ad_id;

COMMIT;
