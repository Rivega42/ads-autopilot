import type { CampaignEntryCheck } from '@/campaigns/index.js';

/**
 * Штатные состояния клиента: команда ответила, чинить нечего.
 *
 * «Уже создано» — работа сделана; «карточка ждёт решения» — система дошла до
 * человека и ждёт нажатия. Ненулевой код на них означал бы поломку, а в скрипте,
 * обходящем клиентов, читался бы именно так — и разбудил бы дежурного из-за
 * кампании, которая исправно работает.
 */
const SETTLED: ReadonlySet<CampaignEntryCheck['kind']> = new Set([
  'ready',
  'already_created',
  'awaiting_decision',
]);

/**
 * Нужно ли вмешательство человека, чтобы запуск вообще стал возможен.
 *
 * Это и есть смысл ненулевого кода возврата: не «ответ отрицательный», а «без
 * тебя дальше не поедет» — дыра в брифе, отсутствующий токен, незавершённая
 * попытка создания, неизвестный клиент в аргументе.
 *
 * Недоставленная карточка — тоже «не поедет», и не важно, в каком состоянии она
 * застала клиента. Пока правило смотрело только на `awaiting_decision`, дыра была
 * ровно там, где её больнее всего: вход возвращает это состояние, только пока
 * жива хотя бы одна карточка, а когда Telegram не принял ни одной, состояние
 * снова `ready` — и дешёвый прогон без `--apply`, которым и ходят по клиентам
 * скриптом, отчитывался «готов» именно в том случае, ради которого код возврата
 * и правился.
 */
export function needsHumanFix(check: CampaignEntryCheck): boolean {
  if (check.kind === 'ready' || check.kind === 'awaiting_decision') {
    return check.undelivered.length > 0;
  }
  return !SETTLED.has(check.kind);
}
