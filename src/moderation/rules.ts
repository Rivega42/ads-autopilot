/**
 * Капслок как приём выделения: слово целиком из кириллических заглавных, не входящее
 * в список общепринятых аббревиатур.
 *
 * Ограничений три, и каждое снимает свой класс ложных срабатываний:
 *  • только кириллица — латинские слова в русском объявлении почти всегда либо
 *    аббревиатура (IELTS, CRM, SEO), либо бренд, и отличить их детектором нельзя;
 *  • только слово целиком — иначе «МФЦ» внутри «МФЦентр» тоже считалось бы криком;
 *  • от четырёх букв и мимо словаря — трёхбуквенные аббревиатуры и перечисленные
 *    выше отсекаются до проверки.
 */
