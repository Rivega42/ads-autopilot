/**
 * База правил модерации (TZ §13.4, пункт 3).
 *
 * В ТЗ написано «200+ правил». Здесь их 38, и это осознанно: правило, которое
 * «объясняет» отказ, но которого нет ни в законе, ни в опубликованных требованиях
 * площадки, хуже отсутствующего — модель уверенно перепишет объявление под выдумку,
 * получит второй отказ и сожжёт попытку. Поэтому в базу попало только то, что
 * проверяемо по первоисточнику, и у каждого правила первоисточник указан явно.
 *
 * Источники ровно четыре:
 *  • ФЗ «О рекламе» № 38-ФЗ — общие запреты и требования по тематикам;
 *  • ФЗ № 436-ФЗ — возрастная маркировка информационной продукции;
 *  • опубликованные требования Яндекс Директа к рекламным материалам и текстам;
 *  • опубликованные правила размещения VK Рекламы.
 *
 * Как расширять: одно правило — одно требование одного источника. Если источник
 * назвать нельзя, правило не добавляется. Пополнять базу дешевле, чем разбирать,
 * почему кабинет клиента третий раз получает отказ по несуществующей норме.
 */

