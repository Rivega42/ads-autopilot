/** Сколько правил в базе. Отдельная константа: число попадает в лог и в отчёт человеку. */
export const RULES_COUNT = MODERATION_RULES.length;

/** Уникальные источники — из них строится сноска в письме человеку. */
export function ruleSources(): string[] {
  const seen = new Set<string>();
  for (const rule of MODERATION_RULES) seen.add(rule.source.authority);
  return [...seen];
}

/** Правила категории для конкретного канала. */
export function rulesFor(category: RejectionCategory, channel: Provider): ModerationRule[] {
  return MODERATION_RULES.filter(
    (rule) => rule.category === category && rule.channels.includes(channel),
  );
}

/**
 * Категории, на которые указывает текст причины отказа.
 *
 * Именно подсказка: площадки формулируют причины по-разному и часто одной строкой
 * вроде «Нарушение требований к рекламным материалам». Решение принимает модель,
 * а этот список сужает ей выбор и попадает в промпт.
 */
export function hintCategories(reason: string): RejectionCategory[] {
  const hints = new Set<RejectionCategory>();
  for (const rule of MODERATION_RULES) {
    if (rule.triggers?.some((re) => re.test(reason))) hints.add(rule.category);
  }
  return [...hints];
}

/**
 * Правила, которые уезжают в промпт переписывания: правила категории плюс те,
 * на которые указала сама причина отказа. Площадка может назвать одну претензию,
 * а объявление нарушать две — вторую мы иначе не увидим.
 */
export function rulesForRejection(
  category: RejectionCategory,
  channel: Provider,
  reason: string,
  limit = 12,
): ModerationRule[] {
  const picked = new Map<string, ModerationRule>();
  for (const rule of rulesFor(category, channel)) picked.set(rule.id, rule);
  for (const rule of MODERATION_RULES) {
    if (!rule.channels.includes(channel)) continue;
    if (rule.triggers?.some((re) => re.test(reason))) picked.set(rule.id, rule);
  }
  return [...picked.values()].slice(0, limit);
}

/** Блок для промпта. Формат намеренно плоский: модель читает его как чек-лист. */
export function formatRules(rules: readonly ModerationRule[]): string {
  if (rules.length === 0) return 'Специальных правил под эту категорию в базе нет.';
  return rules
    .map((rule) =>
      [
        `### ${rule.id}`,
        `Требование: ${rule.requirement}`,
        `Как исправить: ${rule.fix}`,
        `Источник: ${rule.source.authority}, ${rule.source.ref}`,
      ].join('\n'),
    )
    .join('\n\n');
}

export interface ForbiddenHit {
  ruleId: string;
  /** Что именно сработало — попадает в заметку для следующей попытки модели. */
  match: string;
}

/**
 * Лексическая проверка готового текста по всем правилам с детектором.
 *
 * Проверяются все правила, а не только правила категории отказа: переписывая
 * медицинский текст, модель охотно вставит «лучшая клиника», и второй отказ
 * придёт уже по другой статье.
 */
export function findForbidden(text: string, channel: Provider): ForbiddenHit[] {
  const hits: ForbiddenHit[] = [];
  for (const rule of MODERATION_RULES) {
    if (!rule.forbidden || !rule.channels.includes(channel)) continue;
    for (const pattern of rule.forbidden) {
      const found = pattern.exec(text);
      if (found) {
        hits.push({ ruleId: rule.id, match: found[0] });
        break;
      }
    }
  }
  return hits;
}
